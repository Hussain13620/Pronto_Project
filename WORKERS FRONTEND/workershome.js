const defaultDashboard = {
    name: "",
    todayEarnings: 0,
    completedJobs: 0,
    rating: 0,
    totalEarnings: 0,
    isOnline: false,
    recentActivity: []
};

function readStoredDashboard() {
    let stored = {};

    try {
        const raw = localStorage.getItem(STORAGE_KEY);
        stored = raw ? JSON.parse(raw) : {};
    } catch (error) {
        stored = {};
    }

    return {
        ...defaultDashboard,
        ...(window.PRONTO_WORKER_DATA || {}),
        ...stored
    };
}

